#!/usr/bin/env python3
"""Build a wheel for the recovered NetEase API client.

Usage::

    python scripts/build_wheel.py                # wheel in dist/
    python scripts/build_wheel.py --clean        # remove build/ and dist/ first
    python scripts/build_wheel.py --sdist        # also build a source archive
    python scripts/build_wheel.py --check        # inspect the wheel and exit
    python scripts/build_wheel.py --out wheels    # custom output directory

The script prefers the `build` package (PEP 517, isolated) and falls back to
`pip wheel --no-build-isolation` when it is not installed.  ``--sdist`` also
produces a source archive; without `build` it is generated by setuptools
directly, so it works offline.  Both artifacts are inspected so test fixtures,
credentials, the APK and the extraction artifacts can never leak into the
distribution.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import shutil
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"

#: Files that must exist inside the wheel.
REQUIRED = {
    "netease_api/__init__.py",
    "netease_api/client.py",
    "netease_api/routes.py",
    "netease_api/cli.py",
    "netease_api/transport.py",
    "netease_api/crypto.py",
    "netease_api/errors.py",
    "netease_api/apis/__init__.py",
}
#: Prefixes that must never appear in the wheel.
FORBIDDEN_PREFIXES = ("tests/", "tools/", "examples/", "extracted/", "docs/")
FORBIDDEN_SUFFIXES = (".apk", ".dex", ".so")

#: Files that must exist inside the source distribution.
SDIST_REQUIRED = {
    "pyproject.toml",
    "API.md",
    "ROUTES.md",
    "README.md",
    "netease_api/__init__.py",
    "netease_api/client.py",
    "netease_api/routes.py",
    "netease_api/transport.py",
    "tests/test_apis.py",
    "tests/test_client.py",
    "docs/conf.py",
}
#: Names that must never appear in the source distribution.
SDIST_FORBIDDEN = (
    "cookies.txt",
    "__pycache__",
    ".pyc",
    ".pyo",
    ".apk",
    ".dex",
    ".7z",
    ".rar",
)


def run(cmd: list[str]) -> int:
    print("+ " + " ".join(cmd))
    return subprocess.run(cmd, cwd=ROOT).returncode


def clean() -> None:
    for path in (ROOT / "build", DIST):
        if path.exists():
            print(f"removing {path}")
            shutil.rmtree(path)
    for egg in ROOT.glob("*.egg-info"):
        print(f"removing {egg}")
        shutil.rmtree(egg)


def build_wheel(out_dir: Path, isolated: bool) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    if importlib.util.find_spec("build"):
        cmd = [sys.executable, "-m", "build", "--wheel", "--outdir", str(out_dir)]
        if not isolated:
            cmd.append("--no-isolation")
        rc = run(cmd)
        if rc == 0:
            return
        if isolated:
            print(
                "note: isolated build failed (offline?); retrying with --no-isolation",
                file=sys.stderr,
            )
            rc = run(cmd + ["--no-isolation"])
        if rc != 0:
            raise SystemExit(f"build failed with exit code {rc}")
        return

    cmd = [
        sys.executable,
        "-m",
        "pip",
        "wheel",
        ".",
        "--no-deps",
        "--wheel-dir",
        str(out_dir),
    ]
    if not isolated:
        cmd.append("--no-build-isolation")
    rc = run(cmd)
    if rc != 0 and isolated:
        print(
            "note: isolated build failed (offline?); retrying without build isolation",
            file=sys.stderr,
        )
        rc = run(cmd + ["--no-build-isolation"])
    if rc != 0:
        raise SystemExit(f"build failed with exit code {rc}")


def build_sdist(out_dir: Path) -> None:
    """Build the source distribution (``.tar.gz``) without network access.

    ``python -m build`` is not always installed and its isolated environment
    needs network access, so setuptools' PEP 517 backend is called directly as
    a fallback.  It reads ``pyproject.toml`` and ``MANIFEST.in`` exactly as a
    PEP 517 frontend would.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    if importlib.util.find_spec("build"):
        cmd = [sys.executable, "-m", "build", "--sdist", "--outdir", str(out_dir)]
        rc = run(cmd)
        if rc == 0:
            return
        print(
            "note: isolated sdist failed (offline?); retrying with --no-isolation",
            file=sys.stderr,
        )
        rc = run(cmd + ["--no-isolation"])
    else:
        print("note: the `build` package is not installed; using setuptools directly")
        code = (
            "import setuptools.build_meta as backend;"
            f"print(backend.build_sdist({str(out_dir)!r}))"
        )
        rc = run([sys.executable, "-c", code])
    if rc != 0:
        raise SystemExit(f"sdist build failed with exit code {rc}")


def newest_wheel(out_dir: Path) -> Path:
    wheels = sorted(out_dir.glob("*.whl"), key=lambda p: p.stat().st_mtime)
    if not wheels:
        raise SystemExit(f"no wheel found in {out_dir}")
    return wheels[-1]


def check_wheel(wheel: Path) -> None:
    print(f"\ninspecting {wheel.name}")
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
    missing = sorted(REQUIRED - set(names))
    if missing:
        raise SystemExit("wheel is missing required files: " + ", ".join(missing))
    bad = [
        name
        for name in names
        if name.startswith(FORBIDDEN_PREFIXES) or name.endswith(FORBIDDEN_SUFFIXES)
    ]
    if bad:
        raise SystemExit("wheel contains forbidden files: " + ", ".join(bad))

    metadata = next((n for n in names if n.endswith(".dist-info/METADATA")), None)
    if metadata is None:
        raise SystemExit("wheel has no METADATA")
    with zipfile.ZipFile(wheel) as archive:
        text = archive.read(metadata).decode("utf-8", "replace")
    fields = {}
    for line in text.splitlines():
        if ": " in line:
            key, value = line.split(": ", 1)
            fields.setdefault(key, value)
    print(f"  name:     {fields.get('Name')}")
    print(f"  version:  {fields.get('Version')}")
    print(f"  files:    {len(names)}")
    print(f"  requires: {fields.get('Requires-Dist', '(none)')}")

    digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
    print(f"  sha256:   {digest}")
    print(f"  size:     {wheel.stat().st_size:,} bytes")


def newest_sdist(out_dir: Path) -> Path:
    sdists = sorted(out_dir.glob("*.tar.gz"), key=lambda p: p.stat().st_mtime)
    if not sdists:
        raise SystemExit(f"no sdist found in {out_dir}")
    return sdists[-1]


def check_sdist(sdist: Path) -> None:
    print(f"\ninspecting {sdist.name}")
    with tarfile.open(sdist, "r:gz") as archive:
        entries = archive.getnames()
        names = {
            name.split("/", 1)[1]
            for name in entries
            if "/" in name and name.split("/", 1)[1]
        }
        pkginfo = next(
            (name for name in entries if name.endswith("/PKG-INFO") or name == "PKG-INFO"),
            None,
        )
        metadata = ""
        if pkginfo:
            extracted = archive.extractfile(pkginfo)
            if extracted is not None:
                metadata = extracted.read().decode("utf-8", "replace")

    missing = sorted(SDIST_REQUIRED - names)
    if missing:
        raise SystemExit("sdist is missing required files: " + ", ".join(missing))
    bad = sorted(
        name
        for name in names
        if name.endswith(SDIST_FORBIDDEN)
        or "/cookies.txt" in "/" + name
        or "__pycache__" in name
        or name.startswith(("build/", "dist/"))
        or "/_build/" in "/" + name
    )
    if bad:
        raise SystemExit("sdist contains forbidden files: " + ", ".join(bad))
    if len(entries) != len(set(entries)):
        raise SystemExit("sdist contains duplicate entries")

    fields = {}
    for line in metadata.splitlines():
        if ": " in line:
            key, value = line.split(": ", 1)
            fields.setdefault(key, value)
    digest = hashlib.sha256(sdist.read_bytes()).hexdigest()
    print(f"  name:     {fields.get('Name', '(unknown)')}")
    print(f"  version:  {fields.get('Version', '(unknown)')}")
    print(f"  files:    {len(entries)}")
    print(f"  sha256:   {digest}")
    print(f"  size:     {sdist.stat().st_size:,} bytes")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out", type=Path, default=DIST, help="output directory (default: dist/)"
    )
    parser.add_argument("--clean", action="store_true", help="remove build/ and dist/ first")
    parser.add_argument("--sdist", action="store_true", help="also build an sdist")
    parser.add_argument(
        "--no-isolation",
        action="store_true",
        help="build without an isolated environment (no network)",
    )
    parser.add_argument(
        "--check", action="store_true", help="only inspect the newest existing wheel"
    )
    args = parser.parse_args(argv)
    out_dir = args.out if args.out.is_absolute() else ROOT / args.out

    if args.clean:
        clean()
    if not args.check:
        build_wheel(out_dir, isolated=not args.no_isolation)
        if args.sdist:
            build_sdist(out_dir)
    wheel = newest_wheel(out_dir)
    check_wheel(wheel)
    if args.sdist:
        sdist = newest_sdist(out_dir)
        check_sdist(sdist)
        print(f"\nsdist: {sdist}")
    print(f"\nwheel: {wheel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
